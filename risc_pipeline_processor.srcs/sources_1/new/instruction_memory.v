`timescale 1ns / 1ps

// ============================================================================
// Instruction Memory
//
// 256 words × 32 bits = 1 KB
//
// Word-aligned addressing:
// address[9:2]
// ============================================================================

module instruction_memory (

    input  [31:0] address,
    output [31:0] instruction

);

    // ========================================================================
    // Memory
    // ========================================================================

    reg [31:0] mem [0:255];

    wire [7:0] word_addr;

    assign word_addr = address[9:2];


    // ========================================================================
    // Asynchronous instruction read
    // ========================================================================

    assign instruction = mem[word_addr];


    // ========================================================================
    // TEST PROGRAM
    // ========================================================================

    integer i;

    initial begin

        // --------------------------------------------------------------------
        // Initialize entire instruction memory with NOP
        // --------------------------------------------------------------------

        for (i = 0; i < 256; i = i + 1) begin
            mem[i] = 32'h00000000;
        end


        // ====================================================================
        // PROGRAM
        // ====================================================================

        // --------------------------------------------------------------------
        // 0: R1 = 5
        // --------------------------------------------------------------------

        mem[0] = 32'h20010005;
        // ADDI R1, R0, 5


        // --------------------------------------------------------------------
        // 1: R2 = 10
        // --------------------------------------------------------------------

        mem[1] = 32'h2002000A;
        // ADDI R2, R0, 10


        // --------------------------------------------------------------------
        // 2: R3 = R1 + R2 = 15
        //
        // Tests forwarding.
        // --------------------------------------------------------------------

        mem[2] = 32'h00221820;
        // ADD R3, R1, R2


        // --------------------------------------------------------------------
        // 3: R4 = R3 + R1 = 20
        //
        // Tests forwarding from the previous ALU result.
        // --------------------------------------------------------------------

        mem[3] = 32'h00612020;
        // ADD R4, R3, R1


        // --------------------------------------------------------------------
        // 4: MEM[0] = R4 = 20
        //
        // Tests SW.
        // --------------------------------------------------------------------

        mem[4] = 32'hAC040000;
        // SW R4, 0(R0)


        // --------------------------------------------------------------------
        // 5: R5 = MEM[0] = 20
        //
        // Tests LW.
        // --------------------------------------------------------------------

        mem[5] = 32'h8C050000;
        // LW R5, 0(R0)


        // --------------------------------------------------------------------
        // 6: R6 = R5 + R1 = 25
        //
        // IMPORTANT:
        // This immediately uses the result of LW.
        //
        // Therefore this instruction must cause a LOAD-USE STALL.
        // --------------------------------------------------------------------

        mem[6] = 32'h00A13020;
        // ADD R6, R5, R1


        // --------------------------------------------------------------------
        // 7: R7 = R6 + R1 = 30
        //
        // Tests forwarding after the load-use stall.
        // --------------------------------------------------------------------

        mem[7] = 32'h00C13820;
        // ADD R7, R6, R1


        // --------------------------------------------------------------------
        // 8: BEQ R7, R7, +2
        //
        // R7 == R7, therefore branch is ALWAYS taken.
        //
        // Branch target:
        //
        // PC+4 + (2 << 2)
        //
        // Instruction 8:
        // PC = 32
        //
        // PC+4 = 36
        //
        // Target = 36 + 8 = 44
        //
        // 44 / 4 = instruction 11
        // --------------------------------------------------------------------

        mem[8] = 32'h10E70002;
        // BEQ R7, R7, 2


        // --------------------------------------------------------------------
        // 9: WRONG PATH
        //
        // Must NOT execute.
        // --------------------------------------------------------------------

        mem[9] = 32'h200800FF;
        // ADDI R8, R0, 255


        // --------------------------------------------------------------------
        // 10: WRONG PATH
        //
        // Must NOT execute.
        // --------------------------------------------------------------------

        mem[10] = 32'h200900EE;
        // ADDI R9, R0, 238


        // --------------------------------------------------------------------
        // 11: BRANCH TARGET
        //
        // R10 = 42
        // --------------------------------------------------------------------

        mem[11] = 32'h200A002A;
        // ADDI R10, R0, 42


        // --------------------------------------------------------------------
        // 12: JUMP
        //
        // Jump to instruction 14.
        //
        // Address = 14 × 4 = 56
        // Target field = 56 / 4 = 14
        // --------------------------------------------------------------------

        mem[12] = 32'h0800000E;
        // J 14


        // --------------------------------------------------------------------
        // 13: WRONG PATH
        //
        // Must NOT execute.
        // --------------------------------------------------------------------

        mem[13] = 32'h200B00AA;
        // ADDI R11, R0, 170


        // --------------------------------------------------------------------
        // 14: JUMP TARGET
        //
        // R12 = 99
        // --------------------------------------------------------------------

        mem[14] = 32'h200C0063;
        // ADDI R12, R0, 99


        // --------------------------------------------------------------------
        // Remaining memory stays NOP.
        // --------------------------------------------------------------------

    end

endmodule